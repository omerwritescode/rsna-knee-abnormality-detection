"""Build kaggle/submit_notebook.ipynb with the current source files embedded.

    python scripts/build_submit_notebook.py

Embeds src/kneeprep/* and src/models/{data,embed,folds,metrics,m1,predict}.py via
%%writefile cells, so the Kaggle run uses exactly the code in this repo. Rebuild after any
change to those files. Model files come from the Kaggle dataset made by
scripts/make_model_dataset.py.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "kaggle" / "submit_notebook.ipynb"
FILES = [
    "src/__init__.py",
    "src/kneeprep/__init__.py",
    "src/kneeprep/core.py",
    "src/models/__init__.py",
    "src/models/data.py",
    "src/models/embed.py",
    "src/models/folds.py",
    "src/models/metrics.py",
    "src/models/m1.py",
    "src/models/m2.py",
    "src/models/predict.py",
]

MD_INTRO = """# RSNA Knee — submission (M1 frozen DINOv2-S + aggregator, M2 fine-tuned DINOv2-S)

**Settings:** Accelerator **GPU T4** (not P100) · Internet **Off** · Inputs: the competition data and the \
private dataset `rsna-knee-models` (from `scripts/make_model_dataset.py`).

**Run All** first: with the 3 example test studies it finishes in a few minutes and writes \
`submission.csv`. Then **Save Version** (Save & Run All) and submit that version. During scoring Kaggle \
reruns it on the ~1,300 hidden test studies.

Pipeline: DICOM → `kneeprep` (CPU pool) → M1 (frozen DINOv2-S features + aggregator) and/or M2 \
(fine-tuned DINOv2-S; frozen blocks shared across folds) fold ensembles with left/right-mirror TTA → \
weighted blend from `blend.json` → `submission.csv`. Uses whichever of `m1/`, `m2/` the dataset contains. A study that fails at any step gets the training prevalence, so \
the run never crashes. Generated by `scripts/build_submit_notebook.py` — edit the repo, not this notebook."""

CELL_CONFIG = """import os, sys, subprocess, time
T_START = time.time()
TIME_LIMIT_H = 8.0          # stop embedding new studies after this; the rest get priors
WORKERS = os.cpu_count()    # CPU processes for DICOM decoding"""

CELL_FIND = """SKIP = {"train_series", "test_series", "train_images", "test_images"}

def find(predicate, top="/kaggle/input", max_depth=6):
    hits = []
    top_depth = top.rstrip("/").count("/")
    for root, dirs, files in os.walk(top):
        dirs[:] = [d for d in dirs if d not in SKIP]
        if root.count("/") - top_depth >= max_depth:
            dirs[:] = []
        if predicate(root, files):
            hits.append(root)
    return hits

DATA_ROOT = find(lambda r, f: "test_series.csv" in f and "sample_submission.csv" in f)
MODEL_DIR = find(lambda r, f: "priors.json" in f)
WHEELS = find(lambda r, f: any(x.endswith(".whl") for x in f))
assert DATA_ROOT, "competition data not found - Add Input -> Competitions"
assert MODEL_DIR, "model dataset not found - Add Input -> Datasets -> rsna-knee-models"
DATA_ROOT, MODEL_DIR = DATA_ROOT[0], MODEL_DIR[0]
print("data:", DATA_ROOT, "| models:", MODEL_DIR, "| wheels:", WHEELS[:1])
print("python", sys.version.split()[0], "| CPUs", os.cpu_count())
subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"])"""

CELL_INSTALL = """if WHEELS:
    r = subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-index",
                        "--find-links", WHEELS[0], "pydicom", "pylibjpeg", "pylibjpeg-libjpeg",
                        "pylibjpeg-openjpeg", "python-gdcm"], capture_output=True, text=True)
    print("wheel install:", "ok" if r.returncode == 0 else "FAILED\\n" + r.stderr[-1500:])
else:
    print("no wheels found - using the preinstalled packages")
import pydicom, timm, torch
print("pydicom", pydicom.__version__, "| timm", timm.__version__, "| torch", torch.__version__)
for mod in ("pylibjpeg", "openjpeg", "libjpeg", "gdcm"):
    try:
        __import__(mod); print("  decoder available:", mod)
    except Exception:
        print("  decoder MISSING:", mod)"""

CELL_DIRS = """for d in ("src/kneeprep", "src/models"):
    os.makedirs(f"/kaggle/working/{d}", exist_ok=True)
for f in EMPTY_FILES:              # empty package markers (%%writefile needs a body)
    open(f"/kaggle/working/{f}", "w").close()"""

CELL_RUN = """sys.path.insert(0, "/kaggle/working")
from src.models.predict import run_test

remaining_h = TIME_LIMIT_H - (time.time() - T_START) / 3600
sub = run_test(DATA_ROOT, MODEL_DIR, "/kaggle/working/submission.csv",
               workers=WORKERS, time_limit_h=remaining_h)
print(sub.shape)
print(sub.head())
print(sub.drop(columns="StudyInstanceUID").describe().T[["mean", "std", "min", "max"]])"""


def code(src: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": src.splitlines(keepends=True)}


def md(src: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


def main() -> None:
    file_cells, empty = [], []
    for rel in FILES:
        path = ROOT / rel
        if not path.exists() and not rel.endswith("__init__.py"):
            raise SystemExit(f"missing {rel}")
        text = path.read_text(encoding="utf-8") if path.exists() else ""
        if text.strip():
            file_cells.append(code(f"%%writefile /kaggle/working/{rel}\n{text}"))
        else:
            empty.append(rel)
    dirs_cell = f"EMPTY_FILES = {empty!r}\n" + CELL_DIRS
    cells = [md(MD_INTRO), code(CELL_CONFIG), code(CELL_FIND), code(CELL_INSTALL), code(dirs_cell),
             md("## Source files (embedded from the repo)"), *file_cells]
    cells += [md("## Predict the test set"), code(CELL_RUN)]
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                      "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 4}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {OUT} ({len(cells)} cells, {sum(len(c['source']) for c in cells)} lines)")


if __name__ == "__main__":
    main()
