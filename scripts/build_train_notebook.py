def code(src: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": src.splitlines(keepends=True)}


def md(src: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


def main() -> None:
    file_cells = []
    for rel in FILES:
        text = (ROOT / rel).read_text(encoding="utf-8")
        file_cells.append(code(f"%%writefile /tmp/code/{rel}\n{text}"))
    cells = [md(MD_INTRO), code(CELL_CONFIG), code(CELL_FIND), code(CELL_SETUP),
             md("## Source files (embedded from the repo)"), *file_cells,
             md("## Train"), code(CELL_RUN), code(CELL_COLLECT)]
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                      "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 4}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {OUT} ({len(cells)} cells, {sum(len(c['source']) for c in cells)} lines)")


if __name__ == "__main__":
    main()
