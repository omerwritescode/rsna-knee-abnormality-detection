CELL_RUN = r"""import shlex, signal, threading, re
from datetime import datetime

TASKS = [(run, k, f"{COMMON} {extra}".strip()) for run, folds, extra in JOBS for k in folds]
NAMES = [j[0] for j in JOBS]
assert TASKS, "JOBS is empty"
assert len(set(NAMES)) == len(NAMES), "each job needs its own run name"

def flag(args, name, default):
    fl = shlex.split(args)
    idx = [i for i, x in enumerate(fl) if x == name]
    return type(default)(fl[idx[-1] + 1]) if idx else default

for run, k, a in TASKS:                          # pseudo-label files must be present
    tl = flag(a, "--train-labels", "")
    assert not tl or os.path.exists(f"{WORK}/data/labels/{tl}"), \
        f"{run}: {tl} not found - attach the rsna-knee-score output that wrote it"
print("tasks:", ", ".join(f"{r} f{k}" for r, k, _ in TASKS))

def run_dir(run):
    d = f"{OUT_ROOT}/{run}"
    os.makedirs(d, exist_ok=True)
    return d

def launch(run, k, args, gpu, extra=()):
    cmd = [sys.executable, "-m", "src.models.m2", "--root", WORK, "--name", run, "--folds", str(k),
           "--weights", WEIGHTS, "--workers", str(WORKERS_PER_GPU), *shlex.split(args), *extra]
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), PYTHONUNBUFFERED="1")
    fh = open(f"{run_dir(run)}/stdout_f{k}.txt", "w")
    print(f"[{time.strftime('%H:%M')}] {run} fold {k} -> GPU {gpu}", flush=True)
    return subprocess.Popen(cmd, cwd=CODE, env=env, stdout=fh, stderr=subprocess.STDOUT,
                            start_new_session=True), fh

def read_log(run, k):
    p = f"{OUT_ROOT}/{run}/train_f{k}.log"
    return open(p, encoding="utf-8").read() if os.path.exists(p) else ""

def tail(run, k):
    lines = [l.rstrip() for l in read_log(run, k).splitlines() if l.strip()]
    return lines[-1] if lines else "(no log yet)"

def gpu_line():
    r = subprocess.run(["nvidia-smi", "--query-gpu=index,memory.used,memory.total,utilization.gpu",
                        "--format=csv,noheader"], capture_output=True, text=True)
    return " | ".join(l.strip() for l in r.stdout.strip().splitlines())

def elapsed_h():
    return (time.time() - T_START) / 3600

PROG = re.compile(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d),\d+\s+fold \d+ ep 1\s+(\d+)/(\d+)\s+loss [\d.]+"
                  r"\s+(\d+) img/s\s+epoch ETA ([\d.]+) min", re.M)

def epoch_minutes(log):
    hits = PROG.findall(log)
    if not hits:
        return None, None
    ts = [datetime.strptime(h[0], "%Y-%m-%d %H:%M:%S") for h in hits]
    total, ips = int(hits[-1][2]), hits[-1][3]
    if len(hits) >= 2 and int(hits[-1][1]) > int(hits[0][1]):    # time per step between two lines
        per_step = (ts[-1] - ts[0]).total_seconds() / (int(hits[-1][1]) - int(hits[0][1]))
        return per_step * total / 60, ips
    frac = int(hits[-1][1]) / total
    return float(hits[-1][4]) / max(1 - frac, 0.05), ips

if MODE == "benchmark":
    bench = [(f"bench_{run}_f{k}", run, k, a) for run, k, a in TASKS[:len(GPUS)]]
    procs = [launch(b, k, a, g, ["--epochs", "1", "--log-every", "25"])
             for (b, run, k, a), g in zip(bench, GPUS)]
    for _ in range(BENCH_MIN):
        time.sleep(60)
        print(f"[{time.strftime('%H:%M')}] GPU {gpu_line()}", flush=True)
    for p, fh in procs:
        if p.poll() is None:
            os.killpg(p.pid, signal.SIGTERM)
        p.wait(); fh.close()
    fold_h = {}
    for (b, run, k, a), g in zip(bench, GPUS):
        log = read_log(b, k)
        ep_min, ips = epoch_minutes(log)
        if ep_min is None:
            print(f"{run} fold {k}: no progress lines - output:")
            print(open(f"{OUT_ROOT}/{b}/stdout_f{k}.txt").read()[-3000:])
            continue
        n_ep = flag(a, "--epochs", 6)
        fold_h[run] = ep_min * n_ep * 1.15 / 60          # +15% for validation passes
        amp = re.findall(r"autocast.*", log)
        print(f"{run} fold {k} (GPU {g}): {ips} img/s, ~{ep_min:.1f} min/epoch x {n_ep} epochs "
              f"-> ~{fold_h[run]:.1f} h per fold | {amp[0] if amp else ''}")
        shutil.rmtree(f"{OUT_ROOT}/{b}", ignore_errors=True)
    if fold_h:
        slowest = max(fold_h.values())
        free = [0.0] * len(GPUS)
        for run, k, a in TASKS:                          # same order as the real queue
            g = free.index(min(free))
            free[g] += fold_h.get(run, slowest)
        total = max(free) + 0.1
        guessed = sorted({r for r, _, _ in TASKS} - set(fold_h))
        print(f"\nestimate for MODE='train': ~{total:.1f} h for {len(TASKS)} task(s) on {len(GPUS)} GPU(s) "
              f"(budget {TIME_BUDGET_H} h)" + (f"; {guessed} not measured, assumed as slow as the "
              f"slowest measured job" if guessed else ""))
        if total > TIME_BUDGET_H:
            print("-> too long for one session: tasks that would end after the budget are not started; "
                  "move some to the next session's notebook")
else:
    queue, lock, durations, skipped, results = list(TASKS), threading.Lock(), {}, [], []
    ended = set()                                    # (run, fold) finished or crashed

    def estimate(run):
        own = durations.get(run, [])
        anyrun = [h for v in durations.values() for h in v]
        return max(own or anyrun) if (own or anyrun) else None

    def worker(gpu):
        while True:
            with lock:
                task = None
                while queue:
                    run, k, a = queue.pop(0)
                    est = estimate(run)
                    if est is not None and elapsed_h() + est > TIME_BUDGET_H:
                        skipped.append((run, k))
                        continue
                    task = (run, k, a)
                    break
                if task is None:
                    return
            run, k, a = task
            t0 = time.time()
            p, fh = launch(run, k, a, gpu)
            rc = p.wait(); fh.close()
            ended.add((run, k))
            h = (time.time() - t0) / 3600
            vals = re.findall(r"ep (\d+) .*val auc_llm ([\d.]+)\s+auc_human ([\d.na]+)", read_log(run, k))
            last = f"ep {vals[-1][0]} val auc_llm {vals[-1][1]} auc_human {vals[-1][2]}" if vals else "no val score"
            print(f"[{time.strftime('%H:%M')}] {run} fold {k} finished on GPU {gpu}: exit {rc}, "
                  f"{h:.2f} h | {last}", flush=True)
            if rc != 0:
                print(open(f"{OUT_ROOT}/{run}/stdout_f{k}.txt").read()[-3000:], flush=True)
            else:
                with lock:
                    durations.setdefault(run, []).append(h)
                    results.append((run, k, vals))

    def monitor():
        while True:
            time.sleep(MONITOR_MIN * 60)
            print(f"[{time.strftime('%H:%M')}] GPU {gpu_line()}", flush=True)
    threading.Thread(target=monitor, daemon=True).start()

    threads = [threading.Thread(target=worker, args=(g,)) for g in GPUS]
    for t in threads:
        t.start()
    while any(t.is_alive() for t in threads):        # progress in the version's log
        for t in threads:
            t.join(timeout=600 / len(threads))
        for run, k, _ in TASKS:
            if read_log(run, k) and (run, k) not in ended:
                print(f"[{time.strftime('%H:%M')} | {elapsed_h():.1f} h] {run} fold {k}: {tail(run, k)}",
                      flush=True)
    print(f"\nsession finished in {elapsed_h():.1f} h. Validation scores (auc_llm / auc_human):")
    for run, k, vals in sorted(results):
        print(f"  {run:8s} fold {k}: " + "  ".join(f"ep{e} {v} / {h}" for e, v, h in vals))
    if skipped:
        print(f"NOT started (would exceed {TIME_BUDGET_H} h): {skipped} -> put them in the next "
              f"session's JOBS with the same run name and flags")"""

