CELL_RUN = """import shlex, signal, threading, re

out_dir = f"{OUT_ROOT}/{'bench' if MODE == 'benchmark' else RUN_NAME}"
os.makedirs(out_dir, exist_ok=True)

def launch(k, gpu, extra):
    name = os.path.basename(out_dir)
    cmd = [sys.executable, "-m", "src.models.m2", "--root", WORK, "--name", name,
           "--folds", str(k), "--weights", WEIGHTS, "--workers", str(WORKERS_PER_GPU),
           *shlex.split(M2_ARGS), *extra]
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), PYTHONUNBUFFERED="1")
    fh = open(f"{out_dir}/stdout_f{k}.txt", "w")
    print(f"[{time.strftime('%H:%M')}] fold {k} -> GPU {gpu}", flush=True)
    return subprocess.Popen(cmd, cwd=CODE, env=env, stdout=fh, stderr=subprocess.STDOUT,
                            start_new_session=True), fh

def tail(k, n=1):
    p = f"{out_dir}/train_f{k}.log"
    if not os.path.exists(p):
        return "(no log yet)"
    lines = [l.rstrip() for l in open(p, encoding="utf-8") if l.strip()]
    return " | ".join(lines[-n:]) if lines else "(empty)"

def elapsed_h():
    return (time.time() - T_START) / 3600

if MODE == "benchmark":
    # one fold per GPU, frequent progress lines, stopped after BENCH_MIN minutes
    procs = [launch(k, g, ["--epochs", "1", "--log-every", "25"]) for k, g in zip(FOLDS, GPUS)]
    time.sleep(BENCH_MIN * 60)
    for (p, fh) in procs:
        if p.poll() is None:
            os.killpg(p.pid, signal.SIGTERM)
        p.wait(); fh.close()
    m_args = shlex.split(M2_ARGS)
    epochs = int(m_args[m_args.index("--epochs") + 1]) if "--epochs" in m_args else 6
    ep_min = []
    for k, g in zip(FOLDS, GPUS):
        log = open(f"{out_dir}/train_f{k}.log", encoding="utf-8").read() \\
            if os.path.exists(f"{out_dir}/train_f{k}.log") else ""
        hits = re.findall(r"(\\d+)/(\\d+)\\s+loss [\\d.]+\\s+(\\d+) img/s\\s+epoch ETA ([\\d.]+) min", log)
        if not hits:
            print(f"fold {k}: no progress lines - see {out_dir}/stdout_f{k}.txt")
            print(open(f"{out_dir}/stdout_f{k}.txt").read()[-3000:])
            continue
        it, total, ips, eta = hits[-1]
        done_frac = int(it) / int(total)
        # time per epoch from the last progress line: elapsed-in-epoch + ETA
        per_epoch = float(eta) / (1 - done_frac) if done_frac < 1 else float(eta)
        ep_min.append(per_epoch)
        print(f"fold {k} (GPU {g}): {ips} img/s, step {it}/{total}, ~{per_epoch:.1f} min/epoch")
        for line in re.findall(r".*autocast.*", log)[:1]:
            print("   ", line.strip())
    if ep_min:
        rounds = -(-len(FOLDS) // len(GPUS))
        fold_h = max(ep_min) * epochs * 1.15 / 60           # +15% for validation passes
        print(f"\\nestimate for MODE='train' with {M2_ARGS!r}: ~{fold_h:.1f} h per fold, "
              f"{rounds} rounds on {len(GPUS)} GPU(s) -> ~{rounds * fold_h + 0.2:.1f} h "
              f"(budget {TIME_BUDGET_H} h)")
        if rounds * fold_h + 0.2 > TIME_BUDGET_H:
            per_session = max(1, int((TIME_BUDGET_H - 0.2) // fold_h)) * len(GPUS)
            print(f"-> too long for one session: run about {per_session} folds per session "
                  f"(e.g. FOLDS = {FOLDS[:per_session]}, then the rest), or fewer epochs")
else:
    queue, lock, durations, skipped = list(FOLDS), threading.Lock(), [], []

    def worker(gpu):
        while True:
            with lock:
                if not queue:
                    return
                est = max(durations) if durations else None
                if est is not None and elapsed_h() + est > TIME_BUDGET_H:
                    skipped.extend(queue); queue.clear()
                    return
                k = queue.pop(0)
            t0 = time.time()
            p, fh = launch(k, gpu, [])
            rc = p.wait(); fh.close()
            h = (time.time() - t0) / 3600
            print(f"[{time.strftime('%H:%M')}] fold {k} finished on GPU {gpu}: exit {rc}, "
                  f"{h:.2f} h | {tail(k)}", flush=True)
            if rc != 0:
                print(open(f"{out_dir}/stdout_f{k}.txt").read()[-3000:], flush=True)
            else:
                with lock:
                    durations.append(h)

    threads = [threading.Thread(target=worker, args=(g,)) for g in GPUS]
    for t in threads:
        t.start()
    while any(t.is_alive() for t in threads):        # progress in the version's log
        for t in threads:
            t.join(timeout=600 / len(threads))
        running = [k for k in FOLDS if os.path.exists(f"{out_dir}/train_f{k}.log")
                   and not os.path.exists(f"{out_dir}/fold{k}.pt")]
        for k in running:
            print(f"[{time.strftime('%H:%M')} | {elapsed_h():.1f} h] fold {k}: {tail(k)}", flush=True)
    done = sorted(int(re.findall(r"\\d+", os.path.basename(p))[0])
                  for p in glob.glob(f"{out_dir}/fold*.pt"))
    print(f"\\nfinished folds: {done} in {elapsed_h():.1f} h")
    if skipped:
        print(f"NOT started (would exceed {TIME_BUDGET_H} h): {skipped} -> run them in a new "
              f"session with FOLDS = {skipped}, same RUN_NAME and M2_ARGS")"""

