"""Build kaggle/train_notebook.ipynb: M2 fine-tuning on Kaggle's GPUs (T4 x2).

    python scripts/build_train_notebook.py

Embeds src/models/{data,folds,metrics,m1,m2}.py via %%writefile cells, so the Kaggle run
uses exactly the code in this repo. Rebuild after any change to those files.

Kaggle inputs (no internet needed):
  * notebooks rsna-knee-prep-chunk0 and rsna-knee-prep-chunk1 (the 12 shard tars, 23 GB)
  * dataset rsna-knee-models        (m1/fold*.pt to start from, dinov2/model.safetensors)
  * dataset rsna-knee-train-inputs  (soft_labels.parquet, folds.csv; scripts/make_train_inputs.py)

Each GPU trains one fold at a time (separate processes); folds are handed out from a queue.
A fold is only started if it is expected to finish inside TIME_BUDGET_H (Kaggle stops a
session at 12 h); folds left over are listed so they can run in a later session.
Outputs land in /kaggle/working/m2/<RUN_NAME>/ (fold*.pt, oof_fold*.csv, train_f*.log).
"""
