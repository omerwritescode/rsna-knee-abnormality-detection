"""Build kaggle/train_notebook.ipynb: M2 fine-tuning on Kaggle's GPUs (T4 x2).

    python scripts/build_train_notebook.py

Embeds src/models/{data,folds,metrics,m1,m2}.py via %%writefile cells, so the Kaggle run
uses exactly the code in this repo. Rebuild after any change to those files.

Kaggle inputs (no internet needed):
  * notebooks rsna-knee-prep-chunk0 and rsna-knee-prep-chunk1 (the 12 shard tars, 23 GB)
  * dataset rsna-knee-train-inputs  (labels, folds, m1/fold*.pt to start from,
                                     dinov2/model.safetensors; scripts/make_train_inputs.py)

JOBS lists (run name, folds, extra flags) on top of COMMON flags; every (run, fold) pair is a
task, and each GPU takes the next task when it is free (separate processes), so two
experiments can share one session. A task is only started if it is expected to finish inside
TIME_BUDGET_H (Kaggle stops a session at 12 h); tasks left over are listed for the next
session. Outputs land in /kaggle/working/m2/<run>/ (fold*.pt, oof_fold*.csv, train_f*.log).
Use one notebook per session (rsna-knee-train, -s2, ...): a new version replaces the output.
Pseudo-label files (pseudo_*.parquet) are picked up from any input (rsna-knee-score output).
"""
