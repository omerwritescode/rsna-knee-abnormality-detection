CELL_PSEUDO = """# Pseudo-labels: soften the noisy report labels towards the blended out-of-fold predictions.
# Caveat: a study's OOF prediction comes from models trained on the other 4 folds, so a model
# trained on these targets sees a little of its own validation fold's labels indirectly ->
# CV for runs trained on pseudo-labels is slightly optimistic. The public LB is the fair check.
if PSEUDO:
    b = json.load(open(BLEND))
    w = {b["runs"][k]: v for k, v in b["weights"].items() if v > 0}
    P = None
    for run, wi in w.items():
        o = pd.concat([pd.read_csv(p, dtype={"StudyInstanceUID": str})
                       for p in sorted(glob.glob(f"{TREE}/runs/m2/{run}/oof_fold*.csv"))])
        o = o.drop_duplicates("StudyInstanceUID", keep="last").set_index("StudyInstanceUID")[LABELS]
        P = wi * o if P is None else P + wi * o.reindex(P.index)
    P = P / sum(w.values())
    full = read_labels(Path(f"{LABEL_DIR}/soft_labels.parquet")).set_index("StudyInstanceUID")
    llm = (full["source"] == "llm") & full.index.isin(P.index)
    a = float(PSEUDO["alpha"])
    new = full.copy()
    new.loc[llm, LABELS] = a * full.loc[llm, LABELS].to_numpy() + (1 - a) * P.loc[full.index[llm]].to_numpy()
    os.makedirs(f"{WORKING}/labels", exist_ok=True)
    out = f"{WORKING}/labels/pseudo_{PSEUDO['name']}.parquet"
    new.reset_index().to_parquet(out, index=False)
    old_l, oof_l = full.loc[llm, LABELS], P.loc[full.index[llm]]
    certain = old_l != 0.5
    flip = ((oof_l >= 0.5) != (old_l >= 0.5)) & certain & ((oof_l - 0.5).abs() > 0.35)
    summary = pd.DataFrame({
        "LLM prevalence": old_l.mean(), "OOF mean": oof_l.mean(), "new mean": new.loc[llm, LABELS].mean(),
        "mean |change|": (new.loc[llm, LABELS] - old_l).abs().mean(),
        "strong disagreements %": 100 * flip.sum() / certain.sum()})
    print(f"weights {w}, alpha {a}: {int(llm.sum())} LLM-labelled studies softened, "
          f"{int((full['source'] == 'human').sum())} human labels kept")
    print(summary.to_string(float_format="{:.3f}".format))
    print(f"saved -> {out}  (train with: --train-labels pseudo_{PSEUDO['name']}.parquet)")
else:
    print("PSEUDO = None - no pseudo-labels written")"""

