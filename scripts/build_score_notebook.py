"""Build kaggle/score_notebook.ipynb: score, blend and package M2 runs on Kaggle (CPU only).

    python scripts/build_score_notebook.py

Replaces the laptop steps `m2 --collect`, `blend` and `make_model_dataset`. Embeds
src/models/{folds,metrics,blend}.py via %%writefile cells.

Kaggle inputs (Accelerator None, Internet off):
  * dataset  rsna-knee-train-inputs  labels (+ dinov2 weights, priors.json)
  * dataset  rsna-knee-runs          runs trained on the laptop (m2/<run>/...)
  * notebooks rsna-knee-train, rsna-knee-train-s2, ...   one training notebook per session;
                                     their outputs = runs trained on Kaggle (m2/<run>/...)
  * dataset  rsna-knee-models        only for its wheels/ (pydicom + JPEG decoders)

A run's folds may come from several inputs (e.g. ft3a: fold 0 from the laptop, folds 1-4
from Kaggle); they are merged by run name. Output: /kaggle/working/model_dataset/
(blend.json, m2_<run>/fold*.pt, dinov2/, priors.json, wheels/) -> attach THIS notebook's
output to the submission notebook instead of rsna-knee-models. With PSEUDO set, also
/kaggle/working/labels/pseudo_<name>.parquet (training targets for m2 --train-labels).
Runs with fewer than 5 folds (fold-0 experiments) are scored but not blended or packed.
"""
