CELL_FIND = """def find(predicate, top=INPUT, max_depth=8):
    hits = []
    top_depth = top.rstrip("/").count("/")
    for root, dirs, files in os.walk(top, followlinks=True):
        dirs[:] = [d for d in dirs if d not in {"train_series", "test_series", "train_images", "test_images"}]
        if root.count("/") - top_depth >= max_depth:
            dirs[:] = []
        if predicate(root, files):
            hits.append(root)
    return sorted(hits)

def source_name(path):
    # /kaggle/input/datasets/<user>/<slug>/...  or  /kaggle/input/notebooks/<user>/<slug>/...
    parts = os.path.relpath(path, INPUT).split(os.sep)
    return parts[2] if len(parts) > 2 and parts[0] in ("datasets", "notebooks", "models") else parts[0]

LABEL_DIR = find(lambda r, f: "soft_labels.parquet" in f and "folds.csv" in f)
assert LABEL_DIR, "rsna-knee-train-inputs not found - Add Input -> Datasets"
LABEL_DIR = LABEL_DIR[0]
DINO = [f"{d}/model.safetensors" for d in find(lambda r, f: "model.safetensors" in f and r.endswith("dinov2"))]
DINO.sort(key=lambda p: not p.startswith(LABEL_DIR))               # prefer the train-inputs copy
PRIORS = [f"{d}/priors.json" for d in find(lambda r, f: "priors.json" in f)]
PRIORS.sort(key=lambda p: not p.startswith(LABEL_DIR))           # prefer the train-inputs copy
WHEEL_DIR = find(lambda r, f: any(x.endswith(".whl") for x in f))

RUN_DIRS = {}                                                     # run -> [source dirs]
for d in find(lambda r, f: any(re.fullmatch(r"(oof_)?fold\\d\\.(csv|pt)", x) for x in f)):
    if os.path.basename(d) == "m1" or os.path.basename(d).startswith("m2_"):
        continue                                                  # packaged submission folders
    RUN_DIRS.setdefault(os.path.basename(d), []).append(d)

print("labels :", LABEL_DIR)
print("dinov2 :", DINO[:1] or "NOT FOUND")
print("priors :", PRIORS[:1] or "NOT FOUND")
print("wheels :", WHEEL_DIR[:1] or "NOT FOUND")
print("runs found:")
for run, ds in sorted(RUN_DIRS.items()):
    print(f"  {run:10s} " + " + ".join(source_name(d) for d in ds))
missing = [r for r in RUNS if r not in RUN_DIRS]
assert not missing, f"runs {missing} not in any input - attach the dataset / training notebook that has them\""""

CELL_MERGE = """# One folder per run under TREE/runs/m2/<run>, with symlinks to every source's files.
IGNORE_CFG = {"root", "name", "folds", "bs", "accum", "amp", "workers", "weights", "log_every",
              "eval_every", "eval_start", "collect", "smoke"}
for d in (f"{CODE}/src/models", f"{TREE}/runs/m2", WORKING):
    os.makedirs(d, exist_ok=True)
for f in ("src/__init__.py", "src/models/__init__.py"):
    open(f"{CODE}/{f}", "w").close()

problems = []
for run in RUNS:
    dst = f"{TREE}/runs/m2/{run}"
    shutil.rmtree(dst, ignore_errors=True); os.makedirs(dst)
    origin, cfgs = {}, []
    for src in RUN_DIRS[run]:
        for f in sorted(os.listdir(src)):
            if f.startswith("config") and f.endswith(".json"):
                cfgs.append((f"{source_name(src)}/{f}", json.load(open(f"{src}/{f}"))))
            if not re.fullmatch(r"(oof_)?fold\\d\\.(csv|pt)", f):
                continue
            if os.path.exists(f"{dst}/{f}"):
                problems.append(f"{run}: {f} in both {origin[f]} and {source_name(src)} - using {origin[f]}")
                continue
            os.symlink(f"{src}/{f}", f"{dst}/{f}")
            origin[f] = source_name(src)
    pts = {int(f[4]) for f in origin if f.endswith(".pt")}
    oofs = {int(f[8]) for f in origin if f.endswith(".csv")}
    print(f"{run}:")
    for k in range(5):
        src_k = origin.get(f"fold{k}.pt") or origin.get(f"oof_fold{k}.csv") or "-"
        flags = ("ckpt " if k in pts else "NO-CKPT ") + ("oof" if k in oofs else "NO-OOF")
        print(f"   fold {k}: {flags:12s} from {src_k}")
    if pts != set(range(5)) or oofs != set(range(5)):
        problems.append(f"{run}: incomplete - checkpoints {sorted(pts)}, OOF {sorted(oofs)}")
    if cfgs:                                       # settings that must match across folds
        ref_name, ref = cfgs[0]
        for name, c in cfgs[1:]:
            diff = {k: (ref.get(k), c.get(k)) for k in set(ref) | set(c)
                    if k not in IGNORE_CFG and ref.get(k) != c.get(k)}
            if diff:
                problems.append(f"{run}: {name} differs from {ref_name}: {diff}")
        keep = {k: v for k, v in ref.items() if k not in IGNORE_CFG}
        print("   settings:", ", ".join(f"{k}={keep[k]}" for k in
              ("frozen_blocks", "epochs", "img_size", "slices", "lr_backbone", "init") if k in keep))
print("\\n" + ("\\n".join("WARNING: " + p for p in problems) if problems else "all runs complete and consistent"))"""

CELL_SCORE = """sys.path.insert(0, CODE)
from pathlib import Path
import numpy as np, pandas as pd
from src.models.folds import read_labels
from src.models.metrics import LABELS, score

lab = read_labels(Path(f"{LABEL_DIR}/soft_labels.parquet"))[["StudyInstanceUID", "source", *LABELS]]

def run_score(parts):
    o = pd.concat([pd.read_csv(p, dtype={"StudyInstanceUID": str}) for p in parts])
    df = lab.merge(o, on="StudyInstanceUID", suffixes=("", "_p"))
    return score(df[[f"{l}_p" for l in LABELS]].to_numpy(), df[LABELS].to_numpy(),
                 df["source"].to_numpy()), len(df)

table, per_label, counts = {}, {}, {}
for run in RUNS:
    parts = sorted(glob.glob(f"{TREE}/runs/m2/{run}/oof_fold*.csv"))
    row = {}
    for p in parts:
        sc, _ = run_score([p])
        row[f"fold {p[-5]}"] = sc.loc["MACRO", "auc_llm"]
    sc, n = run_score(parts)
    row["ALL (OOF)"], row["auc_human"] = sc.loc["MACRO", "auc_llm"], sc.loc["MACRO", "auc_human"]
    table[run], per_label[run], counts[run] = row, sc["auc_llm"], n
pd.set_option("display.width", 200)
print("macro auc_llm per fold (auc_human = 58 human studies, noisy):")
print(pd.DataFrame(table).T.to_string(float_format="{:.4f}".format))
print("studies scored:", counts)
pd.DataFrame(table).T.to_csv(f"{WORKING}/scores.csv")"""

CELL_BLEND = """os.makedirs(f"{WORKING}/model_dataset", exist_ok=True)
BLEND = f"{WORKING}/model_dataset/blend.json"
r = subprocess.run([sys.executable, "-m", "src.models.blend", "--root", TREE, "--m1", "none",
                    "--m2", ",".join(RUNS), "--labels", f"{LABEL_DIR}/soft_labels.parquet",
                    "--out", BLEND], cwd=CODE, capture_output=True, text=True)
print(r.stdout[-6000:])
assert r.returncode == 0, r.stderr[-3000:]

if WEIGHTS:                                        # forced weights instead of the best grid
    b = json.load(open(BLEND))
    keys = [f"m2_{run}" for run in RUNS]
    w = np.array([float(WEIGHTS.get(run, 0.0)) for run in RUNS]); w = w / w.sum()
    oofs = []
    for run in RUNS:
        o = pd.concat([pd.read_csv(p, dtype={"StudyInstanceUID": str})
                       for p in sorted(glob.glob(f"{TREE}/runs/m2/{run}/oof_fold*.csv"))])
        oofs.append(o.drop_duplicates("StudyInstanceUID", keep="last").set_index("StudyInstanceUID"))
    common = sorted(set.intersection(*(set(o.index) for o in oofs)))
    P = sum(wi * o.loc[common, LABELS].to_numpy() for wi, o in zip(w, oofs))
    df = lab.set_index("StudyInstanceUID").loc[common]
    sc = score(P, df[LABELS].to_numpy(), df["source"].to_numpy())
    b.update(weights={k: round(float(x), 3) for k, x in zip(keys, w)},
             auc_llm=round(float(sc.loc["MACRO", "auc_llm"]), 4),
             auc_human=round(float(sc.loc["MACRO", "auc_human"]), 4), n_studies=len(common))
    json.dump(b, open(BLEND, "w"), indent=2)
    print(f"FORCED weights {b['weights']} -> auc_llm {b['auc_llm']:.4f}, auc_human {b['auc_human']:.4f}")
print("blend.json:", json.dumps(json.load(open(BLEND))))"""

