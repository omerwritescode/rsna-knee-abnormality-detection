if WEIGHTS:                                        # forced weights instead of the best grid
    b = json.load(open(BLEND))
    keys = [f"m2_{run}" for run in BRUNS]
    w = np.array([float(WEIGHTS.get(run, 0.0)) for run in BRUNS]); w = w / w.sum()
    oofs = []
    for run in BRUNS:
        o = pd.concat([pd.read_csv(p, dtype={"StudyInstanceUID": str})
                       for p in sorted(glob.glob(f"{TREE}/runs/m2/{run}/oof_fold*.csv"))])
